package com.guadian.ondevice.judge

import com.guadian.ondevice.knowledge.LocalKnowledgeJudge
import com.guadian.ondevice.rules.ApkRule
import com.guadian.ondevice.rules.BlocklistRule
import com.guadian.ondevice.rules.BrandImpersonationRule
import com.guadian.ondevice.rules.RuleBasedJudge
import com.guadian.ondevice.rules.SuspiciousUrlRule
import kotlinx.coroutines.runBlocking
import java.io.File

/**
 * Measures how many dataset URLs the JVM-runnable local layers resolve
 * (`CERTAIN`) before page-content inspection, and how many of those verdicts match the
 * dataset label.
 *
 * `PageContentJudge` needs a real WebView and is excluded; the store is
 * excluded because every URL is judged independently.
 *
 * [LocalResolutionTest] checks the measurement's invariants on every test run;
 * [LocalResolutionReportWriter] writes the report, only via
 * `./gradlew :core:judge:writeLocalResolutionReport`.
 */
internal object LocalResolution {
    const val REPORT_PATH = "../../ml/reports/pipeline/local-resolution-report.md"

    private val stages: List<Pair<String, Judge>> = listOf(
        "rules" to RuleBasedJudge(listOf(BlocklistRule(), ApkRule(), BrandImpersonationRule(), SuspiciousUrlRule())),
        "knowledge" to LocalKnowledgeJudge(),
    )

    private val stageLabels = mapOf(
        "rules" to "Deterministic rules",
        "knowledge" to "Local knowledge",
    )

    data class Row(val url: String, val label: String)

    class StageCount(val label: String, var resolved: Int = 0, var correct: Int = 0)

    data class Result(val total: Int, val stages: List<StageCount>, val unresolved: Int, val scope: String = "")

    data class Dataset(val name: String, val scope: String, val file: File)

    fun datasets(): List<Dataset> = listOf(
        Dataset("URL Dataset", "All rows of the committed URL dataset.", File("../../ml/data/url/sample_urls.csv")),
    )

    fun measureAll(): List<Pair<String, Result>> =
        datasets().map { it.name to measure(readRows(it.file)).copy(scope = it.scope) }

    fun measure(rows: List<Row>): Result {
        val counts = stages.associate { (name, _) -> name to StageCount(stageLabels.getValue(name)) }
        var unresolved = 0

        for (row in rows) {
            val resolved = resolve(row.url)
            if (resolved == null) {
                unresolved++
                continue
            }
            val (stage, verdict) = resolved
            val count = counts.getValue(stage)
            count.resolved++
            if (verdict.risk.name == row.label) count.correct++
        }

        return Result(total = rows.size, stages = counts.values.toList(), unresolved = unresolved)
    }

    private fun resolve(url: String): Pair<String, Verdict>? = runBlocking {
        for ((stage, judge) in stages) {
            val verdict = judge.judge(url)
            if (verdict.confidence == Confidence.CERTAIN) return@runBlocking stage to verdict
        }
        null
    }

    fun render(results: List<Pair<String, Result>>): String = buildString {
        appendLine("# Local Resolution Report")
        appendLine()
        appendLine("This report measures how many dataset URLs the local pipeline resolves before")
        appendLine("page-content inspection, and how often those local verdicts")
        appendLine("match the dataset label.")
        appendLine()
        appendLine("## 1. Method")
        appendLine()
        appendLine("Each URL runs through `RuleBasedJudge` and `LocalKnowledgeJudge` in")
        appendLine("pipeline order and counts as resolved at the first")
        appendLine("`CERTAIN` verdict; a resolved verdict is correct when its `risk` equals the")
        appendLine("dataset label. Every URL is judged independently, so the store is excluded.")
        appendLine("`PageContentJudge` is also excluded because it needs a real WebView; the")
        appendLine("unresolved count is therefore what reaches page-content inspection.")
        appendLine()
        appendLine("The report is generated by `LocalResolutionReportWriter`:")
        appendLine()
        appendLine("```bash")
        appendLine("./gradlew :core:judge:writeLocalResolutionReport")
        appendLine("```")
        results.forEachIndexed { index, (name, result) ->
            val resolved = result.stages.sumOf { it.resolved }
            val correct = result.stages.sumOf { it.correct }
            appendLine()
            appendLine("## ${index + 2}. $name")
            appendLine()
            appendLine(
                "${result.scope} Of ${result.total} rows, $resolved (${percent(resolved, result.total)}) resolve locally, " +
                    "and $correct of those (${percent(correct, resolved)}) match the label. " +
                    "The remaining ${result.unresolved} continue to page-content inspection."
            )
            appendLine()
            appendLine("| Stage | Resolved | Correct | Correct / resolved |")
            appendLine("| :-- | --: | --: | --: |")
            for (stage in result.stages) {
                appendLine("| ${stage.label} | ${stage.resolved} | ${stage.correct} | ${percent(stage.correct, stage.resolved)} |")
            }
        }
    }

    private fun percent(part: Int, whole: Int): String =
        if (whole == 0) "0.00%" else "%.2f%%".format(java.util.Locale.ROOT, part * 100.0 / whole)

    fun readRows(file: File): List<Row> {
        val lines = file.readLines().filter { it.isNotBlank() }
        val header = parseCsvLine(lines.first())
        val urlIndex = header.indexOf("url")
        val labelIndex = header.indexOf("label")
        return lines.drop(1).map { line ->
            val fields = parseCsvLine(line)
            Row(url = fields[urlIndex], label = fields[labelIndex])
        }
    }

    private fun parseCsvLine(line: String): List<String> {
        val fields = mutableListOf<String>()
        val current = StringBuilder()
        var inQuotes = false
        var i = 0
        while (i < line.length) {
            val char = line[i]
            when {
                inQuotes && char == '"' && i + 1 < line.length && line[i + 1] == '"' -> {
                    current.append('"')
                    i++
                }
                char == '"' -> inQuotes = !inQuotes
                char == ',' && !inQuotes -> {
                    fields.add(current.toString())
                    current.clear()
                }
                else -> current.append(char)
            }
            i++
        }
        fields.add(current.toString())
        return fields
    }
}
