package com.guadian.ondevice.llm

import com.guadian.ondevice.judge.ReasonCode
import com.guadian.ondevice.verdict.VerdictTable
import java.io.File

/**
 * Measures how many dataset URLs the cache and URL stage settles before the page is
 * opened (docs/design.md, section 3), and how many of those verdicts match the
 * dataset label: [UrlSignals] give the facts, and a URL counts as resolved when the
 * verdict table says the result is final.
 *
 * The store is excluded because every URL is judged independently.
 *
 * [LocalResolutionTest] checks the measurement's invariants on every test run;
 * [LocalResolutionReportWriter] writes the report, only via
 * `./gradlew :core:llm:writeLocalResolutionReport`.
 */
internal object LocalResolution {
    const val REPORT_PATH = "../../ml/reports/pipeline/local-resolution-report.md"

    private val signals = UrlSignals()
    private val table = VerdictTable.default

    data class Row(val url: String, val label: String)

    class ReasonCount(val reason: ReasonCode, var resolved: Int = 0, var correct: Int = 0)

    data class Result(val total: Int, val reasons: List<ReasonCount>, val unresolved: Int, val scope: String = "")

    data class Dataset(val name: String, val scope: String, val file: File)

    fun datasets(): List<Dataset> = listOf(
        Dataset("URL Dataset", "All rows of the committed URL dataset.", File("../../ml/data/url/sample_urls.csv")),
    )

    fun measureAll(): List<Pair<String, Result>> =
        datasets().map { it.name to measure(readRows(it.file)).copy(scope = it.scope) }

    fun measure(rows: List<Row>): Result {
        val counts = linkedMapOf<ReasonCode, ReasonCount>()
        var unresolved = 0
        for (row in rows) {
            val decision = table.decide(signals.inspect(row.url).facts)
            if (!decision.final) {
                unresolved++
                continue
            }
            val reason = reasonOf(decision.reason)
            val count = counts.getOrPut(reason) { ReasonCount(reason) }
            count.resolved++
            if (decision.risk == row.label) count.correct++
        }
        return Result(total = rows.size, reasons = counts.values.toList(), unresolved = unresolved)
    }

    private fun reasonOf(reason: String): ReasonCode = when {
        reason == "blocklisted" -> ReasonCode.BLOCKLISTED
        reason.startsWith("official:") -> ReasonCode.OFFICIAL_SITE
        reason.endsWith(":apk_link") -> ReasonCode.APK_DOWNLOAD
        else -> ReasonCode.IMPERSONATION
    }

    private val LABELS = mapOf(
        ReasonCode.BLOCKLISTED to "On the blocklist",
        ReasonCode.IMPERSONATION to "Certain brand imitation in the host",
        ReasonCode.APK_DOWNLOAD to "`.apk` file off the brand's site",
        ReasonCode.OFFICIAL_SITE to "`.apk` file on the brand's site",
    )

    fun render(results: List<Pair<String, Result>>): String = buildString {
        appendLine("# Local Resolution Report")
        appendLine()
        appendLine("This report measures how many dataset URLs the cache and URL stage settles")
        appendLine("before the page is opened, and how often those verdicts match the dataset label.")
        appendLine()
        appendLine("## 1. Method")
        appendLine()
        appendLine("Each URL's signals come from `UrlSignals` (the blocklist, brand imitation in the")
        appendLine("host, and a URL that is itself an `.apk` file), and the URL counts as resolved when")
        appendLine("the verdict table (`ml/runtime/verdict_table.json`) says the result is final")
        appendLine("whatever the page and the model would show. A resolved verdict is correct when")
        appendLine("its risk equals the dataset label. Every URL is judged independently, so the")
        appendLine("store is excluded; the unresolved count is what goes on to open the page.")
        appendLine()
        appendLine("The report is generated by `LocalResolutionReportWriter`:")
        appendLine()
        appendLine("```bash")
        appendLine("./gradlew :core:llm:writeLocalResolutionReport")
        appendLine("```")
        results.forEachIndexed { index, (name, result) ->
            val resolved = result.reasons.sumOf { it.resolved }
            val correct = result.reasons.sumOf { it.correct }
            appendLine()
            appendLine("## ${index + 2}. $name")
            appendLine()
            appendLine(
                "${result.scope} Of ${result.total} rows, $resolved (${percent(resolved, result.total)}) are settled " +
                    "by the URL alone, and $correct of those (${percent(correct, resolved)}) match the label. " +
                    "The remaining ${result.unresolved} go on to open the page."
            )
            appendLine()
            appendLine("| Settled by | Resolved | Correct | Correct / resolved |")
            appendLine("| :-- | --: | --: | --: |")
            for (count in result.reasons) {
                appendLine("| ${LABELS.getValue(count.reason)} | ${count.resolved} | ${count.correct} | ${percent(count.correct, count.resolved)} |")
            }
        }
    }

    private fun percent(part: Int, whole: Int): String =
        if (whole == 0) "0.00%" else "%.2f%%".format(java.util.Locale.ROOT, part * 100.0 / whole)

    fun readRows(file: File): List<Row> {
        val lines = file.readLines().filter { it.isNotBlank() }
        val header = parseCsvLine(lines.first())
        val urlIndex = header.indexOf("url")
        val labelIndex = header.indexOf("label")
        return lines.drop(1).map { line ->
            val fields = parseCsvLine(line)
            Row(url = fields[urlIndex], label = fields[labelIndex])
        }
    }

    private fun parseCsvLine(line: String): List<String> {
        val fields = mutableListOf<String>()
        val current = StringBuilder()
        var inQuotes = false
        var i = 0
        while (i < line.length) {
            val char = line[i]
            when {
                inQuotes && char == '"' && i + 1 < line.length && line[i + 1] == '"' -> {
                    current.append('"')
                    i++
                }
                char == '"' -> inQuotes = !inQuotes
                char == ',' && !inQuotes -> {
                    fields.add(current.toString())
                    current.clear()
                }
                else -> current.append(char)
            }
            i++
        }
        fields.add(current.toString())
        return fields
    }
}
